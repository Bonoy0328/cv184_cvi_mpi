#!/usr/bin/env python3
"""Reproducible Noto Sans CJK SC subset; Pillow only, no npm/font tools."""
import pathlib
import re
from PIL import Image, ImageDraw, ImageFont
BASE = pathlib.Path(__file__).resolve().parents[1]
FONT = '/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc'
TEXT = '用户管理数据管理信息查询U盘功能门禁设置考勤设置通讯设置高级设置功能菜单数字输入请输入数字清空删除返回菜单门铃功能建设中键盘网线已连接未连接网口不可用未启用检测网线北京时间待校准年月日等待摄像头触控测试请点击四角和中心按下抬起'
TEXT += '工厂屏幕测试模式显示继电器韦根白色补光灯红外暂未实现当前正在处理请稍候请选择项目完成失败已保存恢复原画面切换成功配置存储错误播放音频五秒后自动关闭设备不可用：'
for source in BASE.glob('*.c'):
    if source.name!='fonts.c': TEXT+=''.join(re.findall(r'[\u3000-\u303f\u4e00-\u9fff\uff00-\uffef]',source.read_text()))
TEXT += (BASE/'assets/ime/pinyin.tsv').read_text()
chars = sorted(c for c in set(TEXT + ''.join(chr(i) for i in range(32,127))) if ord(c)>=32)
parts = ['/* Generated by tools/make_fonts.py. Noto CJK, SIL OFL-1.1; see FONT-LICENSE.txt. */', '#include "lvgl.h"']
for size in (20,24):
    font=ImageFont.truetype(FONT,size,index=2)
    height=size+8
    bitmap=[]; glyphs=['{0}']
    for c in chars:
        width=font.getsize(c)[0]
        im=Image.new('L',(width,height))
        ImageDraw.Draw(im).text((0,-size//4),c,font=font,fill=255)
        data=list(im.getdata()); packed=[(data[i]>>4)<<4 | ((data[i+1]>>4) if i+1<len(data) else 0) for i in range(0,len(data),2)]
        glyphs.append('{.bitmap_index=%d,.adv_w=%d,.box_w=%d,.box_h=%d,.ofs_x=0,.ofs_y=0}'%(len(bitmap),width*16,width,height))
        bitmap.extend(packed)
    suffix=str(size)
    parts.append('static const uint8_t bitmap_'+suffix+'[]={\n'+',\n'.join(','.join(str(x) for x in bitmap[i:i+32]) for i in range(0,len(bitmap),32))+'};')
    parts.append('static const lv_font_fmt_txt_glyph_dsc_t glyph_'+suffix+'[]={'+',\n'.join(glyphs)+'};')
    parts.append('static const uint16_t unicode_'+suffix+'[]={'+','.join(str(ord(c)-32) for c in chars)+'};')
    parts.append('static const lv_font_fmt_txt_cmap_t cmap_'+suffix+'[]={ {.range_start=32,.range_length=%d,.glyph_id_start=1,.unicode_list=unicode_%s,.list_length=%d,.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY} };'%(ord(chars[-1])-31,suffix,len(chars)))
    parts.append('static const lv_font_fmt_txt_dsc_t dsc_'+suffix+'={.glyph_bitmap=bitmap_'+suffix+',.glyph_dsc=glyph_'+suffix+',.cmaps=cmap_'+suffix+',.cmap_num=1,.bpp=4,.bitmap_format=0};')
    parts.append('const lv_font_t ky50_font_'+suffix+'={.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height=%d,.base_line=0,.static_bitmap=1,.dsc=&dsc_%s};'%(height,suffix))
(BASE/'fonts.c').write_text('\n'.join(parts)+'\n')
print('Generated',len(chars),'characters at 20/24 px')
